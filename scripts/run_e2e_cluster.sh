#!/usr/bin/env bash
# 最终 E2E 专用集群（高端口，避免与 formal 8080 冲突）
# 拓扑: 2×gw + 2×session + 2×logic + 2×gamedb + globalservice
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

export LUNASERVER_RUN_DIR="${LUNASERVER_RUN_DIR:-$ROOT/run/e2e}"
export LUNASERVER_ADVERTISE_HOST="${LUNASERVER_ADVERTISE_HOST:-127.0.0.1}"
export LUNASERVER_FORMAL="${LUNASERVER_FORMAL:-1}"
export LUNASERVER_HTTP_BIND="${LUNASERVER_HTTP_BIND:-127.0.0.1}"
export LUNASERVER_DRAIN_SEC="${LUNASERVER_DRAIN_SEC:-1}"
# 实验能力默认关闭（稳定版不承诺）
export LUNASERVER_EXPERIMENTAL_PLACEMENT_RECOVERY="${LUNASERVER_EXPERIMENTAL_PLACEMENT_RECOVERY:-0}"
export LUNASERVER_EXPERIMENTAL_DYNAMIC_SCALE="${LUNASERVER_EXPERIMENTAL_DYNAMIC_SCALE:-0}"
export LUNASERVER_EXPERIMENTAL_REGISTRY_OUTAGE="${LUNASERVER_EXPERIMENTAL_REGISTRY_OUTAGE:-0}"
# Placement 自动恢复仅在 experimental=1 时由 ServerBootstrap 注册；下列变量仍可供实验开启时使用
export LUNASERVER_PLACEMENT_SCAN_COUNT="${LUNASERVER_PLACEMENT_SCAN_COUNT:-256}"
export LUNASERVER_PLACEMENT_RECOVER_IV="${LUNASERVER_PLACEMENT_RECOVER_IV:-2}"

# 端口
export LUNASERVER_HTTP_G0="${LUNASERVER_HTTP_G0:-19080}"
export LUNASERVER_GAME_G0="${LUNASERVER_GAME_G0:-19081}"
export LUNASERVER_HTTP_G1="${LUNASERVER_HTTP_G1:-19082}"
export LUNASERVER_GAME_G1="${LUNASERVER_GAME_G1:-19083}"
export LUNASERVER_HTTP_L0="${LUNASERVER_HTTP_L0:-19090}"
export LUNASERVER_LOGIC0="${LUNASERVER_LOGIC0:-19201}"
export LUNASERVER_HTTP_L1="${LUNASERVER_HTTP_L1:-19091}"
export LUNASERVER_LOGIC1="${LUNASERVER_LOGIC1:-19202}"
export LUNASERVER_HTTP_W="${LUNASERVER_HTTP_W:-19092}"
export LUNASERVER_WORLD="${LUNASERVER_WORLD:-19301}"
export LUNASERVER_HTTP_S="${LUNASERVER_HTTP_S:-19093}"
export LUNASERVER_SESSION="${LUNASERVER_SESSION:-19401}"
export LUNASERVER_HTTP_S2="${LUNASERVER_HTTP_S2:-19096}"
export LUNASERVER_SESSION2="${LUNASERVER_SESSION2:-19402}"
export LUNASERVER_HTTP_D0="${LUNASERVER_HTTP_D0:-19094}"
export LUNASERVER_GAMEDB0="${LUNASERVER_GAMEDB0:-19501}"
export LUNASERVER_HTTP_D1="${LUNASERVER_HTTP_D1:-19095}"
export LUNASERVER_GAMEDB1="${LUNASERVER_GAMEDB1:-19502}"

if [[ -f "$LUNASERVER_RUN_DIR/pids" ]]; then
  echo "e2e cluster already running at $LUNASERVER_RUN_DIR (stop: ./scripts/stop_e2e_cluster.sh)"
  exit 1
fi

# 复用 formal 启动器（已含 session×2：sess-0 + sess-1）
./scripts/start_formal.sh

# 写出客户端端口约定
cat >"$LUNASERVER_RUN_DIR/E2E_PORTS.env" <<EOF
export LUNASERVER_RUN_DIR="$LUNASERVER_RUN_DIR"
export E2E_GW0_HTTP=$LUNASERVER_HTTP_G0
export E2E_GW0_GAME=$LUNASERVER_GAME_G0
export E2E_GW1_HTTP=$LUNASERVER_HTTP_G1
export E2E_GW1_GAME=$LUNASERVER_GAME_G1
export E2E_S0_HTTP=$LUNASERVER_HTTP_S
export E2E_S1_HTTP=$LUNASERVER_HTTP_S2
export E2E_L0_HTTP=$LUNASERVER_HTTP_L0
export E2E_L1_HTTP=$LUNASERVER_HTTP_L1
export E2E_DB0_HTTP=$LUNASERVER_HTTP_D0
export E2E_DB1_HTTP=$LUNASERVER_HTTP_D1
export E2E_WORLD_HTTP=$LUNASERVER_HTTP_W
export LUNASERVER_HTTP_L0=$LUNASERVER_HTTP_L0
export LUNASERVER_LOGIC0=$LUNASERVER_LOGIC0
export LUNASERVER_HTTP_L1=$LUNASERVER_HTTP_L1
export LUNASERVER_LOGIC1=$LUNASERVER_LOGIC1
export LUNASERVER_GAME_G0=$LUNASERVER_GAME_G0
export LUNASERVER_GAME_G1=$LUNASERVER_GAME_G1
EOF

echo "run_e2e_cluster.sh PASS"
echo "  source $LUNASERVER_RUN_DIR/E2E_PORTS.env"
echo "  game ports: $LUNASERVER_GAME_G0 / $LUNASERVER_GAME_G1"

# 额外等待：双 Session + Gateway 热通道（失败不阻断启动，由调用方 warm 登录探测）
sleep 1

